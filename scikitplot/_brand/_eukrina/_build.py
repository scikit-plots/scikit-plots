"""
Write Eukrina Mind AI asset sets: logos, colour tokens and a manifest.

See Also
--------
scikitplot._brand._eukrina.render : one asset as SVG text.
scikitplot._brand._kit.verify_manifest : check a written set.

Notes
-----
**User notes:** ``build("out")`` writes every logo of both editions for light
and dark backgrounds, in full colour and one colour, plus CSS and JSON colour
tokens and ``manifest.json``. Running it again rewrites nothing unless an
input changed.

**Developer notes:** file names come only from the fixed vocabularies of
:mod:`._spec`, so nothing a caller passes becomes part of a path except the
output folder itself.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path
from typing import Iterable, Mapping, Sequence, Union

from .._kit._color import SCALE_STEPS, tonal_scale
from .._kit._io import WriteResult, write_bytes, write_manifest
from .._kit._text import find_font, font_info
from ._render import palette, render
from ._spec import EDITIONS, LAYOUTS, THEMES, TYPE, Edition

__all__ = ["BRAND_VERSION", "BuildReport", "asset_name", "build", "tokens"]

#: Version of the brand description; recorded in every manifest.
BRAND_VERSION = "1"

PathLike = Union[str, Path]
_COLORS = ("full", "mono")
_TEXT_LAYOUTS = ("horizontal", "stacked", "wordmark")


@dataclass(frozen=True)
class BuildReport:
    """
    What a build wrote.

    Attributes
    ----------
    root : str
        Output folder.
    files : tuple of WriteResult
        Every asset, the manifest last.
    """

    root: str
    files: tuple[WriteResult, ...]

    @property
    def changed(self) -> int:
        """Number of files whose bytes changed (0 on a repeated build)."""
        return sum(1 for f in self.files if f.changed)


def _pick(
    name: str, values: Iterable[str] | None, allowed: Sequence[str]
) -> tuple[str, ...]:
    if values is None:
        return tuple(allowed)
    if isinstance(values, str):
        values = (values,)
    chosen = tuple(dict.fromkeys(values))
    unknown = [v for v in chosen if v not in allowed]
    if unknown or not chosen:
        raise ValueError(
            f"unknown or empty {name}: {unknown or list(chosen)}; expected some of {list(allowed)}"
        )
    return chosen


def asset_name(
    edition: str, layout: str, theme: str, color: str, text: str = "live"
) -> str:
    """
    Return the relative path of one logo inside a build folder.

    Parameters
    ----------
    edition, layout, theme, color, text : str
        The asset's choices.

    Returns
    -------
    str
        ``"<edition>/svg/eukrina-<layout>-<theme>[-mono][-outline].svg"``;
        ``-outline`` only for layouts with text, since the others are the
        same in both text modes.

    Examples
    --------
    >>> asset_name("blue-green", "horizontal", "dark", "full")
    'blue-green/svg/eukrina-horizontal-dark.svg'
    """
    outlined = text == "outline" and layout in _TEXT_LAYOUTS
    suffix = ("-mono" if color == "mono" else "") + ("-outline" if outlined else "")
    return f"{edition}/svg/eukrina-{layout}-{theme}{suffix}.svg"


def tokens(edition: str | Edition, *, contrast: bool = True) -> dict[str, object]:
    """
    Return the colour tokens of an edition.

    Parameters
    ----------
    edition : str or Edition
        Edition key or object.
    contrast : bool, default True
        Resolve the role colours with the contrast rule.

    Returns
    -------
    dict
        ``{"edition", "name", "colors", "scales", "roles"}``: the edition's
        colours, a 50-950 scale of each (``surface`` and ``on_dark`` have
        none), and per theme the colours the logo uses.
    """
    ed = EDITIONS[edition] if isinstance(edition, str) else edition
    colors = ed.colors()
    roles = {}
    for theme in THEMES:
        pal = palette(ed, theme, contrast=contrast)
        roles[theme] = {
            "background": pal.background,
            "mark": pal.u[1],
            "mark-highlight": pal.u[0],
            "accent": pal.accent[1],
            "accent-light": pal.accent[0],
            "title": pal.title,
            "subtitle": pal.subtitle,
        }
    return {
        "edition": ed.key,
        "name": ed.name,
        "colors": colors,
        "scales": {
            role: {str(step): value for step, value in tonal_scale(color).items()}
            for role, color in colors.items()
            if role not in ("surface", "on_dark")
        },
        "roles": roles,
    }


def _css(data: Mapping[str, object]) -> str:
    key = data["edition"]
    lines = [
        f"/* Eukrina Mind AI - {data['name']} ({key}). Generated by scikitplot._brand._eukrina. */",
        ":root {",
    ]
    for role, color in data["colors"].items():
        lines.append(f"  --eukrina-{role.replace('_', '-')}: {color};")
    for role, scale in data["scales"].items():
        lines.extend(
            f"  --eukrina-{role.replace('_', '-')}-{step}: {scale[str(step)]};"
            for step in SCALE_STEPS
        )
    for name, color in data["roles"]["light"].items():
        lines.append(f"  --eukrina-logo-{name}: {color};")
    lines.append("}")
    lines.append('[data-theme="dark"] {')
    for name, color in data["roles"]["dark"].items():
        lines.append(f"  --eukrina-logo-{name}: {color};")
    lines.append("}")
    return "\n".join(lines) + "\n"


def build(  # noqa: PLR0913
    out_dir: PathLike,
    *,
    editions: Iterable[str] | None = None,
    themes: Iterable[str] | None = None,
    layouts: Iterable[str] | None = None,
    colors: Iterable[str] | None = None,
    text: str = "live",
    font: PathLike | None = None,
    contrast: bool = True,
    with_tokens: bool = True,
) -> BuildReport:
    """
    Write a set of Eukrina Mind AI assets and its manifest.

    Parameters
    ----------
    out_dir : str or pathlib.Path
        Output folder; created if missing. Only files of this build are
        written; nothing else in the folder is touched.
    editions : iterable of str, optional
        Default: all (``"warm-bronze"``, ``"blue-green"``).
    themes : iterable of str, optional
        Default: ``"light"`` and ``"dark"``.
    layouts : iterable of str, optional
        Default: all six layouts.
    colors : iterable of str, optional
        Default: ``"full"`` and ``"mono"``.
    text : {"live", "outline"}, default "live"
        Text mode of the logos (see :func:`render`).
    font : str or pathlib.Path, optional
        Font file for outlines; default the installed Inter SemiBold.
    contrast : bool, default True
        Apply the contrast rule.
    with_tokens : bool, default True
        Also write ``<edition>/tokens.css`` and ``<edition>/tokens.json``.

    Returns
    -------
    BuildReport
        The files written and how many changed.

    Raises
    ------
    ValueError
        For an unknown or empty choice.
    LookupError
        For outlines without ``font`` when Inter is not installed.

    Notes
    -----
    **User notes:** the manifest lists every file with its SHA-256, the
    settings, and, for outlines, the font's name and hash; check a folder
    later with :func:`scikitplot._brand._kit.verify_manifest`.

    **Developer notes:** assets are written in a fixed order and the manifest
    holds no time stamp, so two builds with the same inputs are identical
    byte for byte.

    Examples
    --------
    >>> import tempfile
    >>> with tempfile.TemporaryDirectory() as tmp:
    ...     first = build(tmp, editions=["blue-green"], layouts=["symbol"])
    ...     again = build(tmp, editions=["blue-green"], layouts=["symbol"])
    >>> first.changed > 0, again.changed
    (True, 0)
    """
    chosen_editions = _pick("editions", editions, tuple(EDITIONS))
    chosen_themes = _pick("themes", themes, THEMES)
    chosen_layouts = _pick("layouts", layouts, LAYOUTS)
    chosen_colors = _pick("colors", colors, _COLORS)
    if text not in ("live", "outline"):
        raise ValueError(f"unknown text mode {text!r}; expected 'live' or 'outline'")
    font_file: str | None = None
    if text == "outline":
        font_file = (
            str(font)
            if font is not None
            else find_font(TYPE.outline_family, TYPE.weight)
        )

    root = Path(out_dir)
    results: list[WriteResult] = []
    for edition in chosen_editions:
        for layout in chosen_layouts:
            for theme in chosen_themes:
                for color in chosen_colors:
                    svg = render(
                        layout,
                        edition,
                        theme,
                        color=color,
                        text=text,
                        font=font_file,
                        contrast=contrast,
                    )
                    results.append(
                        write_bytes(
                            root,
                            asset_name(edition, layout, theme, color, text),
                            svg.encode("utf-8"),
                        )
                    )
        if with_tokens:
            data = tokens(edition, contrast=contrast)
            results.append(
                write_bytes(root, f"{edition}/tokens.css", _css(data).encode("ascii"))
            )
            body = json.dumps(data, indent=2, sort_keys=True, ensure_ascii=True) + "\n"
            results.append(
                write_bytes(root, f"{edition}/tokens.json", body.encode("ascii"))
            )

    meta: dict[str, object] = {
        "generator": "scikitplot._brand._eukrina",
        "brand_version": BRAND_VERSION,
        "editions": list(chosen_editions),
        "themes": list(chosen_themes),
        "layouts": list(chosen_layouts),
        "colors": list(chosen_colors),
        "text": text,
        "contrast": contrast,
    }
    if font_file is not None:
        info = font_info(font_file)
        meta["font"] = {
            "family": info.family,
            "style": info.style,
            "sha256": info.sha256,
            "file": Path(font_file).name,
        }
    results.append(write_manifest(root, results, meta))
    return BuildReport(str(root), tuple(results))
