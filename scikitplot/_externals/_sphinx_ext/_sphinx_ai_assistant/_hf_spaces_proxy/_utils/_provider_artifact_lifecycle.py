class RedisProviderArtifactLifecycleRegistry:
    """Shared Redis-backed lifecycle authority with atomic CAS transitions."""

    backend = "redis"
    shared = True
    authoritative = True
    consistency_scope = "single_redis_consistency_domain"

    def __init__(
        self,
        url: str,
        *,
        key_prefix: str = "sphinx-ai-assistant",
        candidate_ttl_seconds: int = PROVIDER_ARTIFACT_CANDIDATE_TTL_SECONDS,
        duplicate_window_seconds: int = PROVIDER_ARTIFACT_DUPLICATE_WINDOW_SECONDS,
        max_records: int = PROVIDER_ARTIFACT_MAX_LIFECYCLE_RECORDS,
        socket_timeout_seconds: float = 2.0,
        require_tls: bool = False,
        client: Any | None = None,
        cancellation_poll_seconds: float = 0.25,
        sweep_interval_seconds: float | None = None,
        operation_attempts: int = PROVIDER_ARTIFACT_REDIS_OPERATION_ATTEMPTS,
        cancellation_watch_failure_limit: int = PROVIDER_ARTIFACT_REDIS_WATCH_FAILURE_LIMIT,
        cluster_mode: bool = False,
    ) -> None:
        if not str(url or "").strip():
            raise ProviderArtifactError("PROVIDER_ARTIFACT_REDIS_URL_REQUIRED")
        self.url = str(url).strip()
        try:
            self._transport, self._connection_kwargs = redis_connection_kwargs(
                self.url,
                require_tls=bool(require_tls),
                socket_timeout_seconds=socket_timeout_seconds,
            )
        except RedisSecurityError as exc:
            raise ProviderArtifactError(f"PROVIDER_ARTIFACT_{exc.code}") from exc
        self._candidate_ttl = max(30, min(int(candidate_ttl_seconds), 24 * 60 * 60))
        self._duplicate_window = max(
            1, min(int(duplicate_window_seconds), self._candidate_ttl)
        )
        self._max_records = max(32, min(int(max_records), 10_000))
        self._poll_seconds = max(0.05, min(float(cancellation_poll_seconds), 2.0))
        self._operation_attempts = max(1, min(int(operation_attempts), 3))
        self._watch_failure_limit = max(
            1, min(int(cancellation_watch_failure_limit), 10)
        )
        self._cluster_mode = bool(cluster_mode)
        if self._cluster_mode and self._transport.database != 0:
            raise ProviderArtifactError(
                "PROVIDER_ARTIFACT_REDIS_CLUSTER_DATABASE_INVALID"
            )
        default_sweep = min(30.0, max(1.0, self._candidate_ttl / 4.0))
        self._sweep_seconds = max(
            0.05,
            min(
                float(
                    sweep_interval_seconds
                    if sweep_interval_seconds is not None
                    else default_sweep
                ),
                60.0,
            ),
        )
        safe = "".join(
            c
            for c in str(key_prefix or "sphinx-ai-assistant").lower()
            if c.isalnum() or c in "_-:"
        )[:64]
        tag = f"{safe or 'sphinx-ai-assistant'}:{{provider-artifact}}"
        self._records_key = f"{tag}:records"
        self._expiry_key = f"{tag}:expiry"
        self._fingerprints_key = f"{tag}:fingerprints"
        self._cancel_key = f"{tag}:cancel"
        self._keys = [
            self._records_key,
            self._expiry_key,
            self._fingerprints_key,
            self._cancel_key,
        ]
        self._client = client
        self._owns = client is None
        self._local_tasks: dict[str, asyncio.Task] = {}
        self._watchers: dict[str, asyncio.Task] = {}
        self._sweeper: asyncio.Task | None = None
        self._local_lock = asyncio.Lock()

    def manifest(self) -> dict[str, object]:
        return {
            "backend": self.backend,
            "shared": True,
            "authoritative": True,
            "consistency_scope": self.consistency_scope,
            "persistence": "ephemeral_shared_metadata",
            "topology": "cluster" if self._cluster_mode else "standalone",
            **self._transport.manifest(),
        }

    async def initialize(self) -> None:
        if self._client is None:
            try:
                if self._cluster_mode:
                    from redis.asyncio.cluster import (  # ruff: ignore[import-outside-top-level]
                        RedisCluster,  # type: ignore[import-not-found]  # ruff: ignore[import-outside-top-level]
                    )

                    self._client = RedisCluster.from_url(
                        self.url, **self._connection_kwargs
                    )
                else:
                    import redis.asyncio as redis_async  # type: ignore[import-not-found]  # ruff: ignore[import-outside-top-level]

                    self._client = redis_async.from_url(
                        self.url, **self._connection_kwargs
                    )
            except Exception as exc:
                raise ProviderArtifactError(
                    "PROVIDER_ARTIFACT_REDIS_DEPENDENCY_UNAVAILABLE"
                ) from exc
        try:
            await self._client.ping()
        except Exception as exc:
            raise ProviderArtifactError("PROVIDER_ARTIFACT_REDIS_UNAVAILABLE") from exc
        await self._cleanup_shared()
        if self._sweeper is None or self._sweeper.done():
            self._sweeper = asyncio.create_task(self._sweep_loop())

    async def _cleanup_shared(self) -> None:
        await self._eval(_REDIS_CLEANUP, [int(time.time())])

    async def _sweep_loop(self) -> None:
        try:
            while True:
                await asyncio.sleep(self._sweep_seconds)
                try:
                    await self._cleanup_shared()
                except ProviderArtifactError:
                    # Route operations remain fail-closed. A transient sweep
                    # failure must not terminate the worker or expose secrets.
                    continue
        except asyncio.CancelledError:
            pass

    async def close(self) -> None:
        async with self._local_lock:
            local_ids = tuple(self._local_tasks)
            tasks = list(self._local_tasks.values()) + list(self._watchers.values())
            if self._sweeper is not None:
                tasks.append(self._sweeper)
                self._sweeper = None
            self._local_tasks.clear()
            self._watchers.clear()
        # Graceful worker shutdown relinquishes only generations owned by this
        # process. Shared records owned by other replicas are never cleared.
        now = int(time.time())
        if self._client is not None:
            for lifecycle_id in local_ids:
                try:  # ruff: ignore[suppressible-exception]
                    await self._eval(
                        _REDIS_FAIL,
                        [
                            lifecycle_id,
                            "cancelled",
                            now + PROVIDER_ARTIFACT_FAILURE_TTL_SECONDS,
                        ],
                    )
                except ProviderArtifactError:  # ruff: ignore[try-except-in-loop]
                    # Shutdown cannot safely broaden into a global cleanup. A
                    # crashed/unreachable store leaves the record to its TTL.
                    pass
        for task in tasks:
            if not task.done():
                task.cancel()
        if tasks:
            await asyncio.gather(*tasks, return_exceptions=True)
        if self._client is not None and self._owns:
            closer = getattr(self._client, "aclose", None) or getattr(
                self._client, "close", None
            )
            if closer:
                result = closer()
                if hasattr(result, "__await__"):
                    await result
            self._client = None

    async def clear(self) -> None:
        """Clear only process-owned tasks; never erase shared Redis authority."""
        async with self._local_lock:
            tasks = list(self._local_tasks.values()) + list(self._watchers.values())
            self._local_tasks.clear()
            self._watchers.clear()
        for task in tasks:
            if not task.done():
                task.cancel()
        if tasks:
            await asyncio.gather(*tasks, return_exceptions=True)

    async def _eval(self, script: str, args: list[Any]) -> tuple[int, str]:
        if self._client is None:
            raise ProviderArtifactError("PROVIDER_ARTIFACT_REDIS_NOT_INITIALIZED")
        last_exc: Exception | None = None
        for attempt in range(self._operation_attempts):
            try:
                out = await self._client.eval(
                    script, len(self._keys), *self._keys, *args
                )
            except ProviderArtifactError:
                raise
            except Exception as exc:
                last_exc = exc
                if attempt + 1 >= self._operation_attempts:
                    raise ProviderArtifactError(
                        "PROVIDER_ARTIFACT_REDIS_OPERATION_FAILED"
                    ) from exc
                # Every lifecycle Lua mutation is retry-idempotent for the same
                # arguments.  This bounds failover/reconnect outcome ambiguity
                # without ever widening authority or generating a new ID.
                await asyncio.sleep(0)
                continue
            _len = len(out) < 2  # ruff: ignore[magic-value-comparison]
            if not isinstance(out, (list, tuple)) or _len:
                raise ProviderArtifactError("PROVIDER_ARTIFACT_REDIS_PROTOCOL_ERROR")
            value = out[1].decode("utf-8") if isinstance(out[1], bytes) else str(out[1])
            return int(out[0]), value
        raise ProviderArtifactError(
            "PROVIDER_ARTIFACT_REDIS_OPERATION_FAILED"
        ) from last_exc

    @staticmethod
    def _public(raw: str) -> dict[str, object]:
        try:
            e = json.loads(raw)
        except Exception as exc:
            raise ProviderArtifactError(
                "PROVIDER_ARTIFACT_REDIS_PROTOCOL_ERROR"
            ) from exc
        return {
            "contract": PROVIDER_ARTIFACT_LIFECYCLE_CONTRACT,
            "lifecycle_id": str(e.get("lifecycle_id") or ""),
            "status": str(e.get("status") or ""),
            "created_at": int(e.get("created_at") or 0),
            "expires_at": int(e.get("expires_at") or 0),
            "regeneration_of": str(e.get("regeneration_of") or "") or None,
        }

    async def begin(
        self, request: ProviderArtifactRequest, *, provider: str, model: str
    ) -> str:
        now = int(time.time())
        fingerprint = ProviderArtifactLifecycleRegistry._fingerprint(request)
        cancel_hash = ProviderArtifactLifecycleRegistry._cancel_hash(
            request.cancel_token
        )
        for _ in range(4):
            lifecycle_id = secrets.token_hex(16)
            ok, val = await self._eval(
                _REDIS_BEGIN,
                [
                    now,
                    lifecycle_id,
                    fingerprint,
                    cancel_hash,
                    request.generator_id,
                    str(provider or ""),
                    str(model or ""),
                    request.kind,
                    request.mime_type,
                    request.prompt_sha256,
                    request.regenerate_of,
                    now + self._candidate_ttl,
                    self._max_records,
                    self._duplicate_window,
                ],
            )
            if ok:
                return lifecycle_id
            mapping = {
                "REGENERATION_INVALID": "PROVIDER_ARTIFACT_REGENERATION_INVALID",
                "DUPLICATE": "PROVIDER_ARTIFACT_DUPLICATE",
                "REQUEST_INVALID": "PROVIDER_ARTIFACT_REQUEST_INVALID",
                "BUSY": "PROVIDER_ARTIFACT_LIFECYCLE_BUSY",
            }
            if val == "COLLISION":
                continue
            raise ProviderArtifactError(
                mapping.get(val, "PROVIDER_ARTIFACT_REDIS_PROTOCOL_ERROR")
            )
        raise ProviderArtifactError("PROVIDER_ARTIFACT_LIFECYCLE_BUSY")

    async def attach_task(self, lifecycle_id: str, task: asyncio.Task) -> None:
        status = await self.public_status(lifecycle_id)
        if status is None or status.get("status") != "generating":
            task.cancel()
            raise ProviderArtifactError("PROVIDER_ARTIFACT_CANCELLED")
        async with self._local_lock:
            self._local_tasks[lifecycle_id] = task
            watcher = asyncio.create_task(self._watch_cancel(lifecycle_id, task))
            self._watchers[lifecycle_id] = watcher

    async def _watch_cancel(self, lifecycle_id: str, task: asyncio.Task) -> None:
        failures = 0
        try:
            while not task.done():
                await asyncio.sleep(self._poll_seconds)
                try:
                    status = await self.public_status(lifecycle_id)
                except ProviderArtifactError:
                    failures += 1
                    if failures >= self._watch_failure_limit:
                        # If shared authority cannot be observed for several
                        # consecutive polls, stop spending provider work rather
                        # than continuing outside the lifecycle control plane.
                        if not task.done():
                            task.cancel()
                        break
                    continue
                failures = 0
                if status is None or status.get("status") != "generating":
                    if (
                        status is not None
                        and status.get("status") == "cancelled"
                        and not task.done()
                    ):
                        task.cancel()
                    break
        except asyncio.CancelledError:
            pass
        finally:
            async with self._local_lock:
                self._watchers.pop(lifecycle_id, None)

    async def _forget_local(self, lifecycle_id: str) -> None:
        async with self._local_lock:
            self._local_tasks.pop(lifecycle_id, None)
            watcher = self._watchers.pop(lifecycle_id, None)
        current = asyncio.current_task()
        if watcher is not None and watcher is not current and not watcher.done():
            watcher.cancel()

    async def complete(
        self, lifecycle_id: str, receipt: ProviderArtifactReceipt
    ) -> ProviderArtifactReceipt:
        now = int(time.time())
        expires = now + self._candidate_ttl
        ok, val = await self._eval(
            _REDIS_COMPLETE,
            [
                lifecycle_id,
                now,
                expires,
                int(receipt.output_size),
                str(receipt.output_sha256),
                receipt.generator_id,
                receipt.provider,
                receipt.model,
                receipt.kind,
                receipt.mime_type,
                receipt.prompt_sha256,
            ],
        )
        await self._forget_local(lifecycle_id)
        if not ok:
            raise ProviderArtifactError(
                "PROVIDER_ARTIFACT_RECEIPT_INVALID"
                if val == "RECEIPT_INVALID"
                else "PROVIDER_ARTIFACT_CANCELLED"
            )
        public = self._public(val)
        return receipt.with_lifecycle(
            lifecycle_id=lifecycle_id,
            expires_at=int(public["expires_at"]),
            regeneration_of=str(public.get("regeneration_of") or ""),
            state="ready",
        )

    async def fail(self, lifecycle_id: str, *, cancelled: bool = False) -> None:
        now = int(time.time())
        await self._eval(
            _REDIS_FAIL,
            [
                lifecycle_id,
                "cancelled" if cancelled else "failed",
                now + PROVIDER_ARTIFACT_FAILURE_TTL_SECONDS,
            ],
        )
        await self._forget_local(lifecycle_id)

    async def cancel(self, cancel_token: str) -> Mapping[str, object]:
        normalized = str(cancel_token or "").strip().lower()
        _len = len(normalized) != 64  # ruff: ignore[magic-value-comparison]
        if _len or any(ch not in "0123456789abcdef" for ch in normalized):
            raise ProviderArtifactError("PROVIDER_ARTIFACT_CANCEL_INVALID")
        token_hash = ProviderArtifactLifecycleRegistry._cancel_hash(normalized)
        if not token_hash:
            raise ProviderArtifactError("PROVIDER_ARTIFACT_CANCEL_INVALID")
        now = int(time.time())
        ok, val = await self._eval(
            _REDIS_CANCEL,
            [token_hash, now, now + PROVIDER_ARTIFACT_FAILURE_TTL_SECONDS],
        )
        if not ok:
            raise ProviderArtifactError("PROVIDER_ARTIFACT_CANCEL_INVALID")
        public = self._public(val)
        lifecycle_id = str(public["lifecycle_id"])
        async with self._local_lock:
            task = self._local_tasks.get(lifecycle_id)
        if public.get("status") == "cancelled" and task is not None and not task.done():
            task.cancel()
        return public

    async def mark_delivered(self, lifecycle_id: str) -> None:
        await self._eval(_REDIS_MARK_DELIVERED, [lifecycle_id])

    async def public_status(self, lifecycle_id: str) -> Mapping[str, object] | None:
        ok, val = await self._eval(
            _REDIS_GET, [str(lifecycle_id or ""), int(time.time())]
        )
        return self._public(val) if ok else None

    async def validate_zip_correlation(
        self, *, lifecycle_id: str, output_sha256: str, output_size: int
    ) -> Mapping[str, object]:
        status = await self.public_status(lifecycle_id)
        if status is None or status.get("status") not in {"ready", "delivered"}:
            raise ProviderArtifactError("PROVIDER_ARTIFACT_PROVENANCE_INVALID")
        # Full hash/size binding is performed atomically by reserve_zip_correlations.
        reservation, ids = await self.reserve_zip_correlations(
            ((lifecycle_id, output_sha256, output_size),)
        )
        await self.release_zip_reservation(ids, reservation)
        status = await self.public_status(lifecycle_id)
        if status is None:
            raise ProviderArtifactError("PROVIDER_ARTIFACT_PROVENANCE_INVALID")
        return status

    async def reserve_zip_correlations(
        self, correlations: tuple[tuple[str, str, int], ...]
    ) -> tuple[str, tuple[str, ...]]:
        if not correlations:
            return "", ()
        ids = tuple(str(c[0] or "") for c in correlations)
        reservation = secrets.token_hex(16)
        now = int(time.time())
        ok, _ = await self._eval(
            _REDIS_RESERVE,
            [
                now,
                reservation,
                now + PROVIDER_ARTIFACT_ZIP_RESERVATION_TTL_SECONDS,
                json.dumps(
                    [[c[0], str(c[1] or "").lower(), int(c[2])] for c in correlations],
                    separators=(",", ":"),
                ),
            ],
        )
        if not ok:
            raise ProviderArtifactError("PROVIDER_ARTIFACT_PROVENANCE_INVALID")
        return reservation, ids

    async def release_zip_reservation(
        self, lifecycle_ids: tuple[str, ...], reservation_id: str
    ) -> None:
        if not lifecycle_ids or not reservation_id:
            return
        await self._eval(
            _REDIS_RELEASE,
            [
                int(time.time()),
                reservation_id,
                json.dumps(list(lifecycle_ids), separators=(",", ":")),
            ],
        )

    async def mark_applied(
        self, lifecycle_ids: tuple[str, ...], reservation_id: str
    ) -> None:
        if not lifecycle_ids or not reservation_id:
            raise ProviderArtifactError("PROVIDER_ARTIFACT_PROVENANCE_INVALID")
        ok, _ = await self._eval(
            _REDIS_APPLY,
            [reservation_id, json.dumps(list(lifecycle_ids), separators=(",", ":"))],
        )
        if not ok:
            raise ProviderArtifactError("PROVIDER_ARTIFACT_PROVENANCE_INVALID")


def build_provider_artifact_lifecycle_registry(
    backend: str,
    *,
    redis_url: str = "",
    redis_key_prefix: str = "sphinx-ai-assistant",
    redis_timeout_seconds: float = 2.0,
    redis_client: Any | None = None,
    require_redis_tls: bool = False,
    candidate_ttl_seconds: int = PROVIDER_ARTIFACT_CANDIDATE_TTL_SECONDS,
    duplicate_window_seconds: int = PROVIDER_ARTIFACT_DUPLICATE_WINDOW_SECONDS,
    max_records: int = PROVIDER_ARTIFACT_MAX_LIFECYCLE_RECORDS,
    redis_cluster_mode: bool = False,
):
    name = str(backend or "memory").strip().lower()
    if name == "memory":
        return ProviderArtifactLifecycleRegistry(
            candidate_ttl_seconds=candidate_ttl_seconds,
            duplicate_window_seconds=duplicate_window_seconds,
            max_records=max_records,
        )
    if name == "redis":
        return RedisProviderArtifactLifecycleRegistry(
            redis_url,
            key_prefix=redis_key_prefix,
            socket_timeout_seconds=redis_timeout_seconds,
            client=redis_client,
            require_tls=require_redis_tls,
            candidate_ttl_seconds=candidate_ttl_seconds,
            duplicate_window_seconds=duplicate_window_seconds,
            max_records=max_records,
            cluster_mode=redis_cluster_mode,
        )
    raise ProviderArtifactError("PROVIDER_ARTIFACT_LIFECYCLE_BACKEND_INVALID")


