"""
Ephemeral lifecycle state for provider-generated binary artifacts.

Run 145 keeps the Run 144 metadata-only authority while making storage
pluggable.  ``memory`` remains the single-process compatibility backend;
``redis`` provides one atomic consistency domain for multi-worker / multi-replica
deployments.  Neither backend stores prompt text, generated bytes, archive
paths, provider credentials, or provider request/response bodies.
"""

