REPO = Path(__file__).resolve().parents[2]
RECORDS = REPO / "maintenances/_repo/_maintenance/tools/check_records.py"

#: Paths of the target that this script owns; everything else is left alone.
MANAGED = (
    ".claude-plugin",
    "skills",
    "agents",
    "assets",
    "LICENSES",
    "README.md",
    "LICENSE",
    ".gitignore",
)
#: The published tree's own ``.gitignore``. A repository template's (GitHub's
#: Python one names ``.pypirc`` and package-index hosts) made the directory's
#: scanner hold the plugin for a credential read (CI-8); this one names only
#: files no plugin ships.
GITIGNORE = """# Generated by tools/maint_tools/build_skills_repo.py; do not edit (Rule 166).
.DS_Store
Thumbs.db
desktop.ini
__pycache__/
"""
ICON_SOURCE = "docs/source/logos/assets/scikit-plots-primary.png"
ICON = "assets/icon.png"
LICENSE_SOURCE = "LICENSE.txt"
LICENSES_SOURCE = "LICENSES"
#: A released version: PEP 440 final releases and post releases only.
RELEASE = re.compile(r"[0-9]+\.[0-9]+\.[0-9]+(?:\.post[0-9]+)?")

# Limits of the pre-submission checklist (see the module docstring).
MAX_FILES = 512
MAX_TEXT_BYTES = 256 * 1024
MAX_ANY_BYTES = 5 * 1024 * 1024
README_MIN_WORDS = 40
IMAGE_SUFFIXES = (".png", ".jpg", ".jpeg", ".gif", ".webp", ".svg")
OS_JUNK = (".DS_Store", "Thumbs.db", "desktop.ini", "__MACOSX")
WINDOWS_DEVICES = re.compile(r"(?i)(con|prn|aux|nul|com[1-9]|lpt[1-9])(\..*)?")
PNG_MAGIC = b"\x89PNG\r\n\x1a\n"
#: A page that loads a script from the network when opened (the directory
#: review's runtime-fetch check); the published tree ships every script it runs.
REMOTE_SCRIPT = re.compile(
    r"""<script\b[^>]*\bsrc\s*=\s*["']?(?:https?:)?//""", re.IGNORECASE
)

# The directory's policy for a publisher that is not a Verified organization
# (refusals of scikit-plots/skills 246d056: LOCAL_CODE_FILE_TYPE,
# LOCAL_CODE_FRONTMATTER_KEY; LAUNCHER_REGISTRY_REDIRECT, which 246d056 to
# 5b6faa3 drew from `>>>` example transcripts, see _check_code). Anthropic
# does not publish the lists; these are the values the refusals name and the
# keys known to be accepted, so a build that passes here can still be refused,
# never the reverse.
#: File types accepted from any publisher: Markdown, text, JSON, YAML, images.
ALLOWED_SUFFIXES = (
    ".md", ".txt", ".json", ".yaml", ".yml", ".png", ".jpg", ".jpeg", ".gif", ".webp", ".ico",
)
#: Files accepted by name whatever their suffix ("a license ... and .gitignore").
ALLOWED_NAMES = ("LICENSE", ".gitignore")
#: Frontmatter keys of a skill, agent, command or output style, as one line of text.
COMPONENT_KEYS = ("name", "description")
#: Package-manager configuration files (a registry, index, proxy or cache source).
PACKAGE_CONFIG = frozenset(
    {
        ".npmrc", ".yarnrc", ".yarnrc.yml", "bunfig.toml", "pnpm-workspace.yaml",
        "pip.conf", "pip.ini", "uv.toml", "poetry.toml", ".pypirc", ".condarc",
        "config.json",
    }
)
#: Text that changes a package manager's configuration, sets an index,
#: registry, link page or VCS/URL source (``-i``, ``--index``, ``-f``,
#: ``--find-links``, ``name @ git+...``), or names one of its configuration
#: files or ``VIRTUAL_ENV``. "The directory resolves pins from the public
#: registry only"; a git URL also runs whatever its branch holds that day.
PACKAGE_SOURCE = re.compile(
    r"(?i)\b(?:npm|pnpm|yarn|bun|pip|uv|conda) config (?:set|edit)\b"
    r"|--(?:extra-)?index-url\b|--registry\b|--trusted-host\b"
    r"|--index\b|--find-links\b|(?<!\S)-[if]\s+(?:https?://|file:)"
    r"|(?<![\w.+-])(?:git|hg|svn|bzr)\+(?:https?|ssh|git|file)://"
    r"|\b(?:PIP_(?:EXTRA_)?INDEX_URL|UV_(?:EXTRA_)?INDEX_URL|NPM_CONFIG_REGISTRY|VIRTUAL_ENV)\b"
    r"|(?<![\w.-])(?:" + "|".join(re.escape(n) for n in sorted(PACKAGE_CONFIG)) + r")\b"
)
#: An opening or closing code fence of a Markdown file, and its info string.
_FENCE = re.compile(r"(`{3,}|~{3,})(.*)")
#: Fence languages whose code is Python source; any other block is read as commands.
PYTHON_FENCES = frozenset({"python", "python3", "py"})


def _code_blocks(text: str) -> list[tuple[str, int, list[str]]]:
    """
    Return the fenced code blocks of a Markdown text.

    Parameters
    ----------
    text : str
        Markdown source.

    Returns
    -------
    list of tuple of (str, int, list of str)
        Per block: its language (the info string's first word, lowercase,
        ``""`` when absent), the 1-based line number of its first code line,
        and its code lines.

    Notes
    -----
    **Developer notes.** A block closes at a line holding only the opening
    fence's character, at least as many times (CommonMark); an unclosed block
    runs to the end of the text. Fences are found after any indentation, so a
    block inside a list item is read too.
    """
    blocks: list[tuple[str, int, list[str]]] = []
    fence = ""
    for number, line in enumerate(text.split("\n"), 1):
        stripped = line.strip()
        if not fence:
            opened = _FENCE.fullmatch(stripped)
            if opened:
                fence = opened.group(1)
                words = opened.group(2).split()
                blocks.append((words[0].lower() if words else "", number + 1, []))
        elif len(stripped) >= len(fence) and set(stripped) == {fence[0]}:
            fence = ""
        else:
            blocks[-1][2].append(line)
    return blocks


def _check_code(rel: str, text: str) -> list[str]:
    """
    Return the code of a Markdown file that does not run as written.

    Parameters
    ----------
    rel : str
        Path of the file in the plugin, for messages.
    text : str
        The file's Markdown source.

    Returns
    -------
    list of str
        One entry per ``python`` block that does not parse with the Python 3.8
        grammar, and per line of any other block that begins with ``>``.

    Notes
    -----
    **User notes.** Write code in a skill as it runs: Python in a ``python``
    block, with expected output as ``# `` comments; commands in a shell block,
    never after a ``>>>`` prompt.

    **Developer notes.** The directory reads skill code as commands. A doctest
    line ``>>> pipeline = f()`` is ``>> > pipeline`` to a shell: a write to a
    file named ``pipeline``, which the directory's policy treats as a possible
    package-manager configuration and blocks (``LAUNCHER_REGISTRY_REDIRECT``,
    on ``skills/scikitplot-corpus/SKILL.md`` from 246d056 to 5b6faa3; the next
    build, whose only change was these examples, passed). A ``python`` block
    is parsed instead of scanned, so a docstring that shows ``>>>`` inside
    Python code passes, and a transcript or a shell command written as Python
    fails (Rule 170).
    """
    errors: list[str] = []
    for language, first, lines in _code_blocks(text):
        if language in PYTHON_FENCES:
            try:
                ast.parse(textwrap.dedent("\n".join(lines)), feature_version=(3, 8))
            except SyntaxError as exc:
                errors.append(
                    f"{rel}:{first + (exc.lineno or 1) - 1}: a python block that does"
                    f" not parse as Python ({exc.msg}); write the code as it runs"
                )
            continue
        errors.extend(
            f"{rel}:{first + offset}: a code line that begins with '>', which a shell"
            " reads as a write to a file (LAUNCHER_REGISTRY_REDIRECT); write the code"
            " as it runs, Python in a python block"
            for offset, line in enumerate(lines)
            if line.lstrip().startswith(">")
        )
    return errors


_TOP_KEY = re.compile(r"([A-Za-z0-9_-]+):(.*)")
_LIST_ITEM = re.compile(r"\s+-\s+(\S.*)")


def _records():
    spec = importlib.util.spec_from_file_location(
        "_check_records_for_skills_repo", RECORDS
    )
    module = importlib.util.module_from_spec(spec)
    sys.modules.setdefault(spec.name, module)
    spec.loader.exec_module(module)
    return module


def _json(data: dict) -> bytes:
    return (json.dumps(data, indent=2, ensure_ascii=False) + "\n").encode("utf-8")


def check_version(version: str) -> str:
    """
    Return *version* when it is a released scikit-plots version.

    Parameters
    ----------
    version : str
        The library version, without a leading ``v`` (``0.5.0``, ``0.5.0.post1``).

    Returns
    -------
    str
        *version*, unchanged.

    Raises
    ------
    ValueError
        When *version* is a development, pre-release or malformed version: the
        released plugin describes a release that ``pip install`` can get.
    """
    if not isinstance(version, str) or not RELEASE.fullmatch(version):
        raise ValueError(
            f"version {version!r} is not a release such as '0.5.0' or '0.5.0.post1';"
            " the released plugin describes a scikit-plots release (Rule 166)"
        )
    return version


def _split_frontmatter(rel: str, text: str) -> tuple[list[str], str]:
    """Return the frontmatter lines and the body of a component file."""
    if not text.startswith("---\n") or "\n---\n" not in text[3:]:
        raise ValueError(f"{rel}: no closed YAML frontmatter")
    end = text.index("\n---\n", 3)
    return text[4:end].split("\n"), text[end + 5 :]


def community_component(rel: str, text: str) -> str:
    """
    Return a skill or agent file as the directory accepts it from any publisher.

    Parameters
    ----------
    rel : str
        Path of the file in the plugin (``skills/<name>/SKILL.md`` or
        ``agents/<name>.md``), for messages.
    text : str
        The file as generated in this repository.

    Returns
    -------
    str
        The same file with only ``name`` and ``description`` in its
        frontmatter. An agent that preloaded its skill (``skills:``, Rule 165)
        instead tells Claude to load it first.

    Raises
    ------
    ValueError
        When a kept key is not one line of text, or a preloading agent's body
        does not have the generated "preloaded" line to rewrite.

    Notes
    -----
    **Developer notes.** The repository keeps the full frontmatter
    (``metadata.scikitplot-module`` maps a skill to its module for
    ``check_records.py``; the development plugin preloads skills); only the
    published tree is reduced. The rewrite is exact, so a change to the agent
    template fails here instead of publishing an agent that contradicts itself.
    """
    head, body = _split_frontmatter(rel, text)
    kept: dict[str, str] = {}
    preload: list[str] = []
    current = None
    for line in head:
        match = _TOP_KEY.fullmatch(line)
        if match:
            current = match.group(1)
            if current in COMPONENT_KEYS:
                kept[current] = line
            continue
        item = _LIST_ITEM.fullmatch(line)
        if current == "skills" and item:
            preload.append(item.group(1).strip().strip("\"'"))
        elif current in COMPONENT_KEYS and line.strip():
            raise ValueError(f"{rel}: '{current}' is not one line of text")
    for key in COMPONENT_KEYS:
        if not kept.get(key, "").partition(":")[2].strip():
            raise ValueError(f"{rel}: '{key}' is missing or empty")
    for skill in preload:
        old = f"- Start from the preloaded `{skill}` skill."
        if old not in body:
            raise ValueError(f"{rel}: preloads {skill!r} but has no {old!r} line to rewrite")
        body = body.replace(old, f"- Load the `{skill}` skill first; it lists what the module offers.")
    return "---\n" + "\n".join(kept[k] for k in COMPONENT_KEYS) + "\n---\n" + body


def published_license(name: str) -> str:
    """Return the published name of ``LICENSES/<name>``: a ``.txt`` file when it has no accepted suffix."""
    return name if Path(name).suffix.lower() in ALLOWED_SUFFIXES else name + ".txt"


def render(source: Path, version: str | None) -> dict[str, bytes]:
    """
    Return every file of the released plugin, by path in the target.

    Parameters
    ----------
    source : Path
        Root of a scikit-plots checkout whose generated plugin is current.
    version : str
        The library version of that checkout (see :func:`check_version`), or
        ``None`` for an unversioned branch build.

    Returns
    -------
    dict of str to bytes
        Target path to content, for the paths under :data:`MANAGED`.

    Raises
    ------
    ValueError
        When the version is not a release, or the checkout's skills, agents or
        README are stale (``check_records.py`` reports a ``skills`` problem).
    FileNotFoundError
        When the checkout lacks the plugin, the icon or the licenses.
    """
    if version is not None:
        check_version(version)
    records = _records()
    stale = records.check_skills(source)
    if stale:
        raise ValueError(
            "the checkout's generated plugin is not current; run check_records.py"
            " --write-index there first:\n  " + "\n  ".join(stale)
        )
    plugin = source / records.PLUGIN_DIR
    manifest = json.loads(
        (plugin / ".claude-plugin/plugin.json").read_text(encoding="utf-8")
    )
    files: dict[str, bytes] = {}
    for base in ("skills", "agents"):
        for path in sorted((plugin / base).rglob("*")):
            if path.is_file() and "__pycache__" not in path.parts:
                rel = path.relative_to(plugin).as_posix()
                data = path.read_bytes()
                if re.fullmatch(r"skills/[^/]+/SKILL\.md|agents/[^/]+\.md", rel):
                    data = community_component(rel, data.decode("utf-8")).encode("utf-8")
                files[rel] = data
    files["README.md"] = (plugin / "README.md").read_bytes()
    files[ICON] = (source / ICON_SOURCE).read_bytes()
    files["LICENSE"] = (source / LICENSE_SOURCE).read_bytes()
    files[".gitignore"] = GITIGNORE.encode("utf-8")
    for path in sorted((source / LICENSES_SOURCE).iterdir()):
        if path.is_file():
            target = f"LICENSES/{published_license(path.name)}"
            if target in files:
                raise ValueError(f"{target}: two license files publish to this name")
            files[target] = path.read_bytes()
    released = {
        "name": manifest["name"],
        "displayName": manifest.get("displayName", manifest["name"]),
        "description": manifest["description"],
        "author": manifest["author"],
        "homepage": manifest["homepage"],
        "repository": f"https://github.com/{records.STABLE_REPO}",
        "license": manifest["license"],
        "keywords": manifest.get("keywords", []),
        "icon": f"./{ICON}",
    }
    if version is not None:
        released = {**released, "version": version}
    files[".claude-plugin/plugin.json"] = _json(released)
    metadata = {"description": manifest["description"]}
    if version is not None:
        metadata["version"] = version
    files[".claude-plugin/marketplace.json"] = _json(
        {
            "name": records.STABLE_MARKETPLACE,
            "owner": manifest["author"],
            "metadata": metadata,
            "plugins": [
                {
                    "name": manifest["name"],
                    "source": "./",
                    "description": manifest["description"],
                }
            ],
        }
    )
    return files


def _managed_files(out: Path) -> set[str]:
    found = set()
    for top in MANAGED:
        path = out / top
        if path.is_file():
            found.add(top)
        elif path.is_dir():
            found.update(
                p.relative_to(out).as_posix() for p in path.rglob("*") if p.is_file()
            )
    return found


def diff(out: Path, files: dict[str, bytes]) -> list[str]:
    """Return ``+ path``, ``~ path`` and ``- path`` lines from *out* to *files*."""
    present = _managed_files(out)
    changes = [f"- {rel}" for rel in sorted(present - set(files))]
    for rel, data in sorted(files.items()):
        if rel not in present:
            changes.append(f"+ {rel}")
        elif (out / rel).read_bytes() != data:
            changes.append(f"~ {rel}")
    return changes


def apply(out: Path, files: dict[str, bytes]) -> list[str]:
    """Make the managed paths of *out* equal *files*; return the changes."""
    changes = diff(out, files)
    for line in changes:
        rel = line[2:]
        if line.startswith("- "):
            (out / rel).unlink()
        else:
            (out / rel).parent.mkdir(parents=True, exist_ok=True)
            (out / rel).write_bytes(files[rel])
    for top in MANAGED:
        folder = out / top
        if folder.is_dir():
            for sub in sorted(
                folder.rglob("*"), key=lambda p: len(p.parts), reverse=True
            ):
                if sub.is_dir() and not any(sub.iterdir()):
                    sub.rmdir()
    return changes


def _words(markdown: str) -> int:
    return len(re.sub(r"```.*?```", " ", markdown, flags=re.DOTALL).split())


def _check_files(out: Path) -> list[str]:
    """Return the checklist's repository and file problems of *out*."""
    errors: list[str] = []
    entries = [
        p for p in sorted(out.rglob("*")) if ".git" not in p.relative_to(out).parts[:1]
    ]
    files = [p for p in entries if p.is_file() and not p.is_symlink()]
    errors.extend(
        f"{entry.name}: not built by this script; the published tree holds only"
        f" {', '.join(MANAGED)} (remove it)"
        for entry in sorted(out.iterdir())
        if entry.name != ".git" and entry.name not in MANAGED
    )
    if len(files) > MAX_FILES:
        errors.append(
            f"{len(files)} files; the checklist holds a plugin over {MAX_FILES}"
        )
    lowered: dict[str, str] = {}
    for path in entries:
        rel = path.relative_to(out).as_posix()
        name = path.name
        if path.is_symlink():
            errors.append(f"{rel}: a symbolic link; commit regular files")
        if name in OS_JUNK:
            errors.append(f"{rel}: an operating-system file; remove it")
        if (
            ":" in name
            or "\\" in name
            or name.endswith((".", " "))
            or WINDOWS_DEVICES.fullmatch(name)
        ):
            errors.append(f"{rel}: a name that is not valid on Windows and macOS")
        if rel.lower() in lowered:
            errors.append(
                f"{rel}: differs from {lowered[rel.lower()]!r} only by letter case"
            )
        lowered[rel.lower()] = rel
    for path in files:
        rel = path.relative_to(out).as_posix()
        size = path.stat().st_size
        if size > MAX_ANY_BYTES:
            errors.append(f"{rel}: {size} bytes; every file stays under 5 MiB")
        elif size > MAX_TEXT_BYTES and path.suffix.lower() not in IMAGE_SUFFIXES:
            errors.append(
                f"{rel}: {size} bytes; a file that is not an image stays under 256 KiB"
            )
    errors.extend(
        f"{path.relative_to(out).as_posix()}: loads a script from the network; ship it"
        " in the plugin or remove the page"
        for path in files
        if path.suffix.lower() in (".html", ".htm")
        and REMOTE_SCRIPT.search(path.read_text(encoding="utf-8", errors="replace"))
    )
    for path in files:
        rel = path.relative_to(out).as_posix()
        data = path.read_bytes()
        suffix = path.suffix.lower()
        if path.name in PACKAGE_CONFIG:
            errors.append(f"{rel}: a package manager's configuration file")
        if path.name not in ALLOWED_NAMES and suffix not in ALLOWED_SUFFIXES:
            errors.append(
                f"{rel}: not Markdown, text, JSON, YAML or an image; refused from a"
                " publisher that is not a Verified organization"
            )
        if data.startswith(b"#!"):
            errors.append(f"{rel}: starts with #!")
        if suffix in IMAGE_SUFFIXES:
            continue
        if b"\x00" in data:
            errors.append(f"{rel}: holds a NUL byte")
        try:
            text = data.decode("utf-8")
        except UnicodeDecodeError:
            errors.append(f"{rel}: not UTF-8 text")
            continue
        if not rel.startswith("LICENSE"):
            errors.extend(
                f"{rel}:{text.count(chr(10), 0, found.start()) + 1}: names a package"
                f" source ({found.group(0)!r}); link to the package manager's instructions"
                for found in PACKAGE_SOURCE.finditer(text)
            )
        if suffix == ".md":
            errors.extend(_check_code(rel, text))
    errors.extend(
        f"{name}: claude.ai refuses a top-level bin/, and the portal a .gitattributes"
        for name in ("bin", ".gitattributes")
        if (out / name).exists()
    )
    return errors


def _check_manifest(out: Path, versioned: bool = True) -> list[str]:
    """Return the problems of ``plugin.json``, its icon and the README.

    A release (*versioned*) needs a released ``version``; a branch build must
    set none, so Claude Code versions it by commit.
    """
    manifest_path = out / ".claude-plugin/plugin.json"
    if not manifest_path.is_file():
        return [".claude-plugin/plugin.json: missing"]
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    errors = [
        f".claude-plugin/plugin.json: {key!r} is not set"
        for key in ("name", "description", "author", "license", "icon")
        if not manifest.get(key)
    ]
    if not versioned:
        if "version" in manifest:
            errors.append(".claude-plugin/plugin.json: a branch build sets no 'version'")
    elif not manifest.get("version"):
        errors.append(".claude-plugin/plugin.json: 'version' is not set")
    if "dependencies" in manifest:
        errors.append(
            ".claude-plugin/plugin.json: sets 'dependencies'; installed from a marketplace"
            " that does not allow theirs, the plugin would install and fail to load"
            " (check_records.EXTERNAL_DEPENDENCIES)"
        )
    if not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", str(manifest.get("name", ""))):
        errors.append(".claude-plugin/plugin.json: 'name' is not lowercase kebab-case")
    if versioned and manifest.get("version"):
        try:
            check_version(manifest.get("version"))
        except ValueError as exc:
            errors.append(f".claude-plugin/plugin.json: {exc}")
    icon_path = str(manifest.get("icon", ""))
    icon = out / (icon_path[2:] if icon_path.startswith("./") else icon_path)
    if not icon.is_file() or icon.read_bytes()[:8] != PNG_MAGIC:
        errors.append(
            f".claude-plugin/plugin.json: icon {manifest.get('icon')!r} is not a PNG in the plugin"
        )
    readme = out / "README.md"
    if (
        not readme.is_file()
        or _words(readme.read_text(encoding="utf-8")) < README_MIN_WORDS
    ):
        errors.append(
            f"README.md: missing or under {README_MIN_WORDS} words outside code blocks"
        )
    return errors


def _check_components(out: Path) -> list[str]:
    """Return the problems of the skills' frontmatter and the agents' names."""
    records = _records()
    errors: list[str] = []
    skills = sorted(p.parent.name for p in (out / "skills").glob("*/SKILL.md"))
    if not skills:
        errors.append("skills/: no skill")
    for folder in skills:
        rel = f"skills/{folder}/SKILL.md"
        front, problems = records.parse_skill_frontmatter(
            (out / rel).read_text(encoding="utf-8")
        )
        errors.extend(f"{rel}: {p}" for p in problems)
        if front.get("name") != folder:
            errors.append(
                f"{rel}: 'name' {front.get('name')!r} is not its folder {folder!r}"
            )
        if not isinstance(front.get("description"), str) or not front["description"]:
            errors.append(f"{rel}: 'description' is not a single text value")
    for base, pattern in (("skills", "*/SKILL.md"), ("agents", "*.md"), ("commands", "*.md"), ("output-styles", "*.md")):
        for path in sorted((out / base).glob(pattern)):
            rel = path.relative_to(out).as_posix()
            try:
                head, _ = _split_frontmatter(rel, path.read_text(encoding="utf-8"))
            except ValueError as exc:
                errors.append(str(exc))
                continue
            keys = [m.group(1) for m in map(_TOP_KEY.fullmatch, head) if m]
            extra = [k for k in keys if k not in COMPONENT_KEYS]
            if extra or len(head) != len(keys):
                errors.append(
                    f"{rel}: frontmatter beyond one-line {' and '.join(COMPONENT_KEYS)}"
                    f" ({', '.join(extra) or 'a multi-line value'})"
                )
    errors.extend(
        f"agents/{agent.name}: no skill of this name"
        for agent in sorted((out / "agents").glob("*.md"))
        if agent.stem not in skills
    )
    return errors


def validate(out: Path, versioned: bool = True) -> list[str]:
    """
    Check *out* against the directory checks a static tree can answer.

    Parameters
    ----------
    out : Path
        Root of the released plugin (the ``scikit-plots/skills`` checkout).
    versioned : bool, default True
        ``True`` for a release build, ``False`` for a branch build.

    Returns
    -------
    list of str
        Empty when no check fails. Each entry names the path and the rule of
        https://claude.com/docs/plugins/pre-submission-checklist it breaks.

    See Also
    --------
    render : What a build writes; a fresh build passes every check.
    """
    return _check_files(out) + _check_manifest(out, versioned) + _check_components(out)


def main(argv: list[str] | None = None) -> int:
    """Run ``build`` or ``check``; return the process exit code."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[1])
    parser.add_argument("command", choices=("build", "check"))
    parser.add_argument(
        "--out",
        type=Path,
        required=True,
        help="root of the scikit-plots/skills checkout",
    )
    which = parser.add_mutually_exclusive_group(required=True)
    which.add_argument("--version", help="a release, e.g. 0.5.0 (for a vX.Y.Z tag)")
    which.add_argument(
        "--unversioned",
        action="store_true",
        help="a branch build (main, maintenance/X.Y.x): no 'version'",
    )
    parser.add_argument(
        "--source",
        type=Path,
        default=REPO,
        help="scikit-plots checkout (default: this one)",
    )
    args = parser.parse_args(argv)
    try:
        files = render(args.source.resolve(), args.version)
    except (ValueError, FileNotFoundError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    out = args.out.resolve()
    if args.command == "build":
        out.mkdir(parents=True, exist_ok=True)
        changes = apply(out, files)
    else:
        changes = (
            diff(out, files) if out.is_dir() else [f"+ {rel}" for rel in sorted(files)]
        )
    for line in changes:
        print(line)
    errors = validate(out, args.version is not None) if out.is_dir() else []
    for line in errors:
        print(f"error: {line}", file=sys.stderr)
    if errors or (args.command == "check" and changes):
        return 1
    print(
        f"ok   {len(files)} files, "
        + (f"version {args.version}" if args.version else "unversioned")
        + ("" if changes else ", unchanged")
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
