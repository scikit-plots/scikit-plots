#!/usr/bin/env python3
"""Generate the user guide's coverage table from the live registries.

Usage::

    python maintenances/cleanprompt/_maintenance/tools/generate_coverage_docs.py [--check]

Writes ``docs/source/user_guide/cleanprompt/coverage_matrix.inc``, which
``how_it_works.rst`` includes, or with ``--check`` exits 1 when the committed
copy differs from what the registries produce.

Notes
-----
**Developer notes (CP-116).** The table is
:func:`scikitplot.cleanprompt._diagnostics.coverage_matrix` under the default
policy, rendered as an RST list table, so it cannot drift from what the
library does: ``_maintenance/tests/test_coverage_docs.py`` fails until it is
regenerated. The ``.inc`` suffix keeps it out of Sphinx's documents and out
of the guide's page-list check; it exists only to be included.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

#: The generated file, relative to the repository root.
TARGET = Path("docs/source/user_guide/cleanprompt/coverage_matrix.inc")


def _repository_root() -> Path:
    """Return the checkout root: the directory holding ``scikitplot/cleanprompt``."""
    here = Path(__file__).resolve()
    for candidate in here.parents:
        if (candidate / "scikitplot" / "cleanprompt" / "_diagnostics.py").is_file():
            return candidate
    msg = "could not locate the repository root"
    raise SystemExit(msg)


def _yes(value: bool) -> str:
    return "yes" if value else ""


def _found_by(row) -> str:
    """Return the surfaces that find a kind, in words."""
    parts = []
    if row.pattern:
        parts.append("core pattern" + (" (validated)" if row.validated else ""))
    if row.pack_patterns:
        parts.append(
            "pattern in " + ", ".join(f"``{name}``" for name in row.pack_patterns)
        )
    if row.pack_fields:
        parts.append("field in " + ", ".join(f"``{name}``" for name in row.pack_fields))
    if row.entity:
        parts.append("entity engine" + ("" if row.entity_default else " (on request)"))
    if row.runtime:
        parts.append("the runtime")
    return "; ".join(parts)


def render(rows) -> str:
    """Return the RST list table for ``rows``."""
    lines = [
        ".. This file is generated by",
        "   maintenances/cleanprompt/_maintenance/tools/generate_coverage_docs.py;",
        "   do not edit it by hand.",
        "",
        ".. list-table::",
        "   :header-rows: 1",
        "   :widths: 22 58 10 10",
        "",
        "   * - Kind",
        "     - Found by",
        "     - Default",
        "     - Stand-in",
    ]
    for row in rows:
        lines += [
            f"   * - ``{row.kind}``",
            f"     - {_found_by(row)}",
            f"     - {_yes(row.default_on or row.entity_default)}",
            f"     - {_yes(row.surrogate)}",
        ]
    # An empty cell is a bare "-": no trailing whitespace in the file.
    return "\n".join(line.rstrip() for line in lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    """Write or check the generated table."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if stale")
    args = parser.parse_args(argv)
    root = _repository_root()
    sys.path.insert(0, str(root))
    from scikitplot.cleanprompt._diagnostics import (  # ruff: ignore[import-outside-top-level]
        coverage_matrix,
    )

    text = render(coverage_matrix())
    target = root / TARGET
    if args.check:
        current = target.read_text(encoding="utf-8") if target.is_file() else ""
        if current != text:
            sys.stderr.write(f"{TARGET} is stale; regenerate it\n")
            return 1
        return 0
    target.write_text(text, encoding="utf-8")
    sys.stdout.write(f"wrote {TARGET}: {len(text.splitlines())} lines\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
