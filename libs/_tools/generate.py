def _validate(distributions, packages: dict[str, object], root: Path) -> None:
    """Check the two registries agree with each other and with the tree."""
    declared = [dist.name for dist in distributions.DISTRIBUTIONS]
    if sorted(declared) != sorted(packages):
        missing = sorted(set(declared) - set(packages))
        unknown = sorted(set(packages) - set(declared))
        raise ValueError(
            "scikitplot/_distributions.py and libs/_tools/registry.py disagree: "
            f"without packaging facts: {missing}; without an ownership entry: {unknown}"
        )
    for name in declared:
        if distributions.canonicalize_name(name) != name:
            raise ValueError(f"{name!r} is not in canonical form")
        registry.directory_of(name)
    staging.check_ownership(distributions.DISTRIBUTIONS, root / staging.PACKAGE_NAME)

    libs = root / "libs"
    expected = {registry.directory_of(name) for name in declared}
    present = {
        path.name
        for path in libs.iterdir()
        if path.is_dir() and not path.name.startswith(("_", "."))
    }
    stray = sorted(present - expected)
    if stray:
        raise ValueError(
            f"libs/ has directories that are not partial distributions: {stray}. "
            "Declare them in scikitplot/_distributions.py and "
            "libs/_tools/registry.py, or remove them."
        )


def expected_files(root: Path | None = None) -> dict[str, str]:
    """
    Return every generated file and its content.

    Parameters
    ----------
    root : pathlib.Path, optional
        Repository root. Defaults to the repository this file belongs to.

    Returns
    -------
    dict of str to str
        POSIX path relative to the repository root, to file content.

    Raises
    ------
    ValueError
        If the inputs are inconsistent: the two registries disagree, a file
        has two owners, a dependency or extra is not declared in the root, or
        ``libs/`` holds a directory that is not a declared distribution.
    FileNotFoundError
        If an owned path does not exist.
    """
    root = staging.repo_root() if root is None else Path(root)
    distributions = staging.load_distributions(root)
    packages = registry.by_distribution()
    _validate(distributions, packages, root)
    meta = read_root_metadata(root)

    files: dict[str, str] = {
        "libs/README.md": render_libs_readme(list(packages.values()), distributions),
        "libs/.gitignore": render_gitignore(),
    }
    for dist in distributions.DISTRIBUTIONS:
        package = packages[dist.name]
        directory = registry.directory_of(dist.name)
        base = f"libs/{directory}"
        files[f"{base}/pyproject.toml"] = render_pyproject(package, distributions, meta)
        files[f"{base}/setup.py"] = render_setup(package)
        files[f"{base}/MANIFEST.in"] = render_manifest(package)
        files[f"{base}/README.md"] = render_readme_directory(package, distributions)
        files[f"{base}/{readme_name(directory)}"] = render_readme_package(
            package, distributions, meta
        )
    return files


def _stale(root: Path, files: dict[str, str]) -> list[str]:
    """Return the generated paths whose content on disk differs."""
    stale = []
    for relative, content in files.items():
        path = root / relative
        if not path.is_file() or path.read_bytes() != content.encode("utf-8"):
            stale.append(relative)
    return stale


def check(root: Path | None = None) -> list[str]:
    """
    Return the generated files that are missing or out of date.

    Parameters
    ----------
    root : pathlib.Path, optional
        Repository root.

    Returns
    -------
    list of str
        Stale paths relative to the repository root; empty when everything is
        up to date. Nothing is written.
    """
    root = staging.repo_root() if root is None else Path(root)
    return _stale(root, expected_files(root))


def generate(root: Path | None = None) -> list[str]:
    """
    Write every generated file that is missing or out of date.

    Parameters
    ----------
    root : pathlib.Path, optional
        Repository root.

    Returns
    -------
    list of str
        The paths written, relative to the repository root; empty when
        everything was already up to date.

    Notes
    -----
    **Developer.** Files are written as UTF-8 with LF line endings on every
    platform, so the output, and therefore ``check``, does not depend on where
    it ran.
    """
    root = staging.repo_root() if root is None else Path(root)
    files = expected_files(root)
    written = _stale(root, files)
    for relative in written:
        path = root / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(files[relative].encode("utf-8"))
    return written
