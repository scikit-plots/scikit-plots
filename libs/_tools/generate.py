_SETUP_TEMPLATE = '''\
# @@NOTICE@@
#
# flake8: noqa: D213
#
# Authors: The scikit-plots developers
# SPDX-License-Identifier: BSD-3-Clause

"""
Build script of ``@@DISTRIBUTION@@``.

``pyproject.toml`` carries the metadata. This script does the one thing
metadata cannot express: it puts the files this distribution owns in front of
the build.

* Inside the repository it copies them from the one ``scikitplot`` source tree
  (``libs/_tools/staging.py`` decides which, from
  ``scikitplot/_distributions.py``) and removes the copy when the build exits.
* Inside an unpacked source distribution the files are already here, and
  nothing is copied.

Either way the package list and the data files are read from what is on disk,
so a wheel built from the repository and one built from the sdist are the same
wheel.
"""

from __future__ import annotations

import atexit
import glob
import importlib.util
import os
import sys
from pathlib import Path

import setuptools
from setuptools import Extension, setup
from setuptools.command.build_ext import build_ext

HERE = Path(__file__).resolve().parent
DISTRIBUTION = "@@DISTRIBUTION@@"
PACKAGE = "scikitplot"
#: SPDX licence expression covering every file this distribution ships.
LICENSE = "@@LICENSE@@"
#: First setuptools major release that understands ``license_expression``
#: (PEP 639); see ``_license_options``.
PEP639_SETUPTOOLS_MAJOR = 77
#: First Cython release with the ``freethreading_compatible`` directive.
CYTHON_FREETHREADING = (3, 1)
#: Compiled extension modules, as declared in libs/_tools/registry.py.
EXTENSIONS = @@EXTENSIONS@@
#: Cython directives of the full distribution's build (root meson.build).
CYTHON_DIRECTIVES = {
    "language_level": 3,
    "wraparound": False,
    "cdivision": True,
    "initializedcheck": False,
    "nonecheck": False,
    "profile": False,
}


def _refuse_editable() -> None:
    """Stop an editable install, which cannot work with staged files."""
    if {"editable_wheel", "develop"} & set(sys.argv[1:]):
        raise SystemExit(
            f"{DISTRIBUTION} cannot be installed in editable mode: its files are "
            "staged for the build and removed afterwards, so an editable install "
            "would point at nothing.\\n"
            "To develop, install the repository root in editable mode instead:\\n"
            "    pip install -e ."
        )


def _stage_from_repository() -> None:
    """Stage the owned files when building from the repository."""
    if (HERE / "PKG-INFO").is_file():
        return  # an unpacked sdist is self-contained
    tools = HERE.parent / "_tools" / "staging.py"
    if not tools.is_file():
        return  # neither; the guard below explains what is wrong
    spec = importlib.util.spec_from_file_location("_skplt_libs_staging", tools)
    staging = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(staging)
    staging.stage(DISTRIBUTION, HERE)
    if os.environ.get("SKPLT_LIBS_KEEP_STAGED") != "1":
        atexit.register(staging.unstage, HERE)


def _packages() -> list:
    """Return every Python package on disk under ``scikitplot/``, sorted."""
    found = []
    for current, dirnames, filenames in os.walk(HERE / PACKAGE):
        dirnames.sort()
        if "__init__.py" in filenames:
            found.append(".".join(Path(current).relative_to(HERE).parts))
    return sorted(found)


def _package_data(packages: list) -> dict:
    """
    Return the non-module files of each outermost package.

    Every file under ``scikitplot/`` reaches the wheel exactly one way: a
    ``.py`` file in a package directory is a module of that package, and any
    other file is data of the outermost package above it. The paths are
    listed, not globbed, so hidden directories are included and no file name
    is read as a pattern.
    """
    known = set(packages)
    data = {}
    for package in packages:
        parts = package.split(".")
        if any(".".join(parts[:n]) in known for n in range(1, len(parts))):
            continue  # covered by an outer package
        base = HERE.joinpath(*parts)
        files = []
        for current, dirnames, filenames in os.walk(base):
            dirnames.sort()
            is_package = "__init__.py" in filenames
            for filename in sorted(filenames):
                if is_package and filename.endswith(".py"):
                    continue
                relative = (Path(current) / filename).relative_to(base).as_posix()
                files.append(glob.escape(relative))
        data[package] = files
    return data


def _require_every_file_shipped(data: dict) -> None:
    """
    Stop the build if a file on disk would not reach the wheel.

    Everything under an outermost package is shipped, as a module or as data.
    A file outside every package directory is neither, and the build would
    drop it without a word. That can only happen when the distribution map
    gives this distribution a file whose directory it does not own, so it is
    reported as the mistake it is.
    """
    roots = [HERE.joinpath(*package.split(".")) for package in data]
    orphans = []
    for current, _dirnames, filenames in os.walk(HERE / PACKAGE):
        here = Path(current)
        if any(root == here or root in here.parents for root in roots):
            continue
        orphans.extend((here / name).relative_to(HERE).as_posix() for name in filenames)
    if orphans:
        raise SystemExit(
            f"{DISTRIBUTION}: these files are not inside any of its packages "
            f"({sorted(data)}) and would be left out of the wheel:\\n  "
            + "\\n  ".join(sorted(orphans))
            + "\\nGive the distribution the package that contains them, or remove "
            "them from scikitplot/_distributions.py."
        )


def _license_options() -> dict:
    """
    Return the licence in the form the running setuptools understands.

    setuptools 77 introduced ``license_expression`` (PEP 639) and deprecated
    every older spelling; releases before 77, the only ones available for
    Python 3.8, know only ``license``. The expression is the same either way.
    """
    if int(setuptools.__version__.split(".")[0]) >= PEP639_SETUPTOOLS_MAJOR:
        return {"license_expression": LICENSE}
    return {"license": LICENSE}


def _render_templates(templates) -> None:
    """
    Render Tempita templates (``name.in`` to ``name``) for the build.

    Cython is imported here, not at the top: it is a build requirement only
    of the distributions that declare an extension.
    """
    from Cython import Tempita  # noqa: PLC0415

    for template in templates:
        source = HERE / template
        target = source.with_name(source.name[: -len(".in")])
        target.write_text(
            Tempita.sub(source.read_text(encoding="utf-8")), encoding="utf-8"
        )


def _translate_cython(extension) -> None:
    """Translate an extension's ``.pyx`` sources to C++, in place."""
    if not any(source.endswith(".pyx") for source in extension.sources):
        return
    import Cython  # noqa: PLC0415
    from Cython.Build import cythonize  # noqa: PLC0415

    release = tuple(int(part) for part in Cython.__version__.split(".")[:2])
    directives = dict(CYTHON_DIRECTIVES)
    if release >= CYTHON_FREETHREADING:
        directives["freethreading_compatible"] = True
    (translated,) = cythonize([extension], compiler_directives=directives, force=True)
    extension.sources = translated.sources


def _extension_options() -> dict:
    """Return the ``setup()`` options for the compiled extensions, if any."""
    if not EXTENSIONS:
        return {}
    declared = {entry["name"]: entry for entry in EXTENSIONS}

    class BuildExt(build_ext):
        """
        Generate the sources, then compile them the way the full build does.

        Nothing is generated until an extension is actually built, so
        metadata-only steps (``egg_info``, ``sdist``) need neither Cython nor
        a compiler.
        """

        def build_extensions(self):
            msvc = self.compiler.compiler_type == "msvc"
            for extension in self.extensions:
                entry = declared[extension.name]
                _render_templates(entry["templates"])
                _translate_cython(extension)
                standard = entry["cxx_standard"]
                if msvc:
                    extension.extra_compile_args += [
                        f"/std:{standard}",
                        # MSVC keeps the ``__cplusplus`` macro at 199711L
                        # whatever ``/std`` says, unless it is told to
                        # report the real value. The vendored Annoy header
                        # checks that macro and stops with "requires at
                        # least C++17" without this.
                        "/Zc:__cplusplus",
                        "/O2",
                        "/bigobj",
                        "/permissive-",
                    ]
                    extension.define_macros += [
                        ("_CRT_SECURE_NO_WARNINGS", None),
                        ("_USE_MATH_DEFINES", None),
                    ]
                else:
                    extension.extra_compile_args += [
                        f"-std={standard}",
                        "-O3",
                        # A release build carries no debug information. Many
                        # interpreters put -g in the flags they hand to
                        # extensions, which multiplies the size of this
                        # template-heavy module several times over.
                        "-g0",
                        "-fno-strict-aliasing",
                    ]
            super().build_extensions()

    return {
        "ext_modules": [
            Extension(
                entry["name"],
                sources=list(entry["sources"]),
                include_dirs=list(entry["include_dirs"]),
                define_macros=[tuple(macro) for macro in entry["define_macros"]],
                language="c++",
            )
            for entry in EXTENSIONS
        ],
        "cmdclass": {"build_ext": BuildExt},
    }


_refuse_editable()
_stage_from_repository()
PACKAGES = _packages()
if not PACKAGES:
    raise SystemExit(
        f"{DISTRIBUTION}: no Python package found under {HERE / PACKAGE}, so this "
        "build would produce a wheel with no code in it.\\n"
        "Build from a checkout of the scikit-plots repository (this directory "
        "must be libs/<name> beside libs/_tools), or from an sdist of this "
        "distribution."
    )

PACKAGE_DATA = _package_data(PACKAGES)
_require_every_file_shipped(PACKAGE_DATA)

setup(
    packages=PACKAGES,
    package_data=PACKAGE_DATA,
    **_license_options(),
    **_extension_options(),
)
'''


def _count(number: int, noun: str) -> str:
    """Return ``"a <noun>"`` for one and ``"<number> <noun>s"`` otherwise."""
    return f"a {noun}" if number == 1 else f"{number} {noun}s"


def _python_literal(value, indent: int = 0) -> str:
    """
    Render plain data as Python source that a formatter leaves alone.

    Parameters
    ----------
    value : None, bool, int, str, list, tuple or dict
        The data. Tuples are rendered as lists; dictionary keys must be
        strings.
    indent : int, default=0
        Indentation, in spaces, of the line the literal starts on.

    Returns
    -------
    str
        The literal. Every non-empty container has one element per line and
        a trailing comma, which is the one layout ``ruff format`` and
        ``black`` both keep as it is whatever its width.

    Raises
    ------
    TypeError
        If ``value`` holds anything else, or a dictionary key is not a string.

    Notes
    -----
    Developer note: the result must not depend on the interpreter that runs
    the generator, or ``check`` would report drift between machines. Strings
    therefore go through :func:`json.dumps` (ASCII, double quotes), whose
    escapes are all valid Python, and nothing here uses :func:`repr`.
    """
    if value is None or isinstance(value, (bool, int, str)):
        # json.dumps spells None, True and False the JSON way; str() does not.
        return (
            json.dumps(value, ensure_ascii=True)
            if isinstance(value, str)
            else str(value)
        )
    pad = " " * (indent + 4)
    if isinstance(value, (list, tuple)):
        opening, closing = "[", "]"
        items = [_python_literal(item, indent + 4) for item in value]
    elif isinstance(value, dict):
        opening, closing = "{", "}"
        items = []
        for key, item in value.items():
            if not isinstance(key, str):
                raise TypeError(
                    f"dictionary keys must be str, got {type(key).__name__}: {key!r}"
                )
            items.append(
                f"{json.dumps(key, ensure_ascii=True)}: "
                f"{_python_literal(item, indent + 4)}"
            )
    else:
        raise TypeError(
            f"cannot render {type(value).__name__} as a Python literal: {value!r}"
        )
    if not items:
        return opening + closing
    body = "".join(f"{pad}{item},\n" for item in items)
    return f"{opening}\n{body}{' ' * indent}{closing}"


def render_setup(package) -> str:
    """
    Render a distribution's ``setup.py``.

    Parameters
    ----------
    package : registry.Package
        The distribution's packaging facts.

    Returns
    -------
    str
        The file content. It is the same for every distribution except for
        the distribution name, the licence and the extension list.

    Raises
    ------
    SyntaxError
        If the rendered script is not valid Python 3.8.
    """
    extensions = _python_literal([ext._asdict() for ext in package.extensions])
    source = (
        _SETUP_TEMPLATE.replace("@@NOTICE@@", GENERATED_NOTICE)
        .replace("@@DISTRIBUTION@@", package.distribution)
        .replace("@@LICENSE@@", package.license)
        .replace("@@EXTENSIONS@@", extensions)
    )
    # A build script that does not parse fails inside the build backend, far
    # from here and with a worse message. Parse it now, with the grammar of
    # the oldest supported interpreter.
    ast.parse(
        source, filename=f"{package.distribution}/setup.py", feature_version=(3, 8)
    )
    return source


def render_manifest(package) -> str:
    """
    Render a distribution's ``MANIFEST.in`` (what its source distribution holds).

    Parameters
    ----------
    package : registry.Package
        The distribution's packaging facts.

    Returns
    -------
    str
        The file content.
    """
    directory = registry.directory_of(package.distribution)
    # No exclusions are needed: the staged tree holds exactly the owned files
    # (staging leaves caches and native build outputs out), so grafting it is
    # exact.
    return "\n".join(
        [
            f"# {GENERATED_NOTICE}",
            f"include {staging.LICENSE_NAME}",
            "include README.md",
            f"include {readme_name(directory)}",
            f"graft {staging.PACKAGE_NAME}",
            "",
        ]
    )


