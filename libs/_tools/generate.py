def _string(value: str) -> str:
    """Render a TOML basic string (JSON string syntax is a subset of it)."""
    return json.dumps(value, ensure_ascii=False)


def _array(values: Sequence[str]) -> str:
    """Render a TOML array of strings, one per line."""
    if not values:
        return "[]"
    return "[\n" + "".join(f"  {_string(value)},\n" for value in values) + "]"


def _people(entries: Sequence[dict[str, str]]) -> str:
    """Render a TOML array of inline ``{name, email}`` tables."""
    rendered = []
    for entry in entries:
        fields = ", ".join(f"{key} = {_string(entry[key])}" for key in sorted(entry))
        rendered.append(f"  {{{fields}}},\n")
    return "[\n" + "".join(rendered) + "]"


def _core_requirement(distributions, version: str) -> str:
    """Return the requirement every non-core distribution has on the core."""
    # A floor and no ceiling: a part imports nothing from the core, so no
    # newer core can break it, while an older core might not know the part
    # exists (its install hints and its ``doctor`` report come from the map
    # the core ships).
    return f"{distributions.CORE}>={version}"


def _build_requires(package, meta: RootMetadata) -> list[str]:
    """Return a distribution's build requirements."""
    return list(registry.BUILD_REQUIRES) + inherit_requirements(
        package.build_inherit, meta.build_requires, "[build-system].requires"
    )


def _dependencies(package, distributions, meta: RootMetadata) -> list[str]:
    """Return a distribution's ``dependencies``."""
    lines: list[str] = []
    if package.distribution != distributions.CORE:
        lines.append(_core_requirement(distributions, meta.version))
    lines.extend(inherit_requirements(package.inherit, meta.dependencies))
    lines.extend(package.requires)
    return lines


def _optional_dependencies(
    package, distributions, meta: RootMetadata
) -> dict[str, list[str]]:
    """Return a distribution's ``optional-dependencies``."""
    groups: dict[str, list[str]] = {}
    full = distributions.FULL
    for name in package.extras:
        if name not in meta.extras:
            raise ValueError(
                f"{package.distribution}: extra {name!r} is not declared in the "
                "root [project.optional-dependencies]"
            )
        for requirement in meta.extras[name]:
            if requirement_name(requirement) == full:
                raise ValueError(
                    f"{package.distribution}: root extra {name!r} requires "
                    f"{requirement!r}, which would install the full distribution; "
                    "it cannot be re-exported by a partial one"
                )
        groups[name] = list(meta.extras[name])
    for name, siblings in package.siblings:
        if name in groups:
            raise ValueError(
                f"{package.distribution}: extra {name!r} is both a root extra and "
                "a sibling extra"
            )
        for sibling in siblings:
            distributions.get(sibling)  # KeyError names the unknown distribution
        groups[name] = [f"{sibling}>={meta.version}" for sibling in siblings]
    return groups


_PYTHON_VERSION_CLASSIFIER = re.compile(
    r"^Programming Language :: Python :: (\d+\.\d+)$"
)


def _classifiers(package, meta: RootMetadata) -> list[str]:
    """
    Return a distribution's classifiers: the inherited ones plus its own.

    A ``Programming Language :: Python :: X.Y`` classifier is inherited only
    for the versions the distribution's ``requires-python`` admits, so the two
    statements about supported versions cannot contradict each other.
    """
    floor = package.requires_python or meta.requires_python
    inherited = []
    for classifier in meta.classifiers:
        if not classifier.startswith(registry.CLASSIFIER_PREFIXES):
            continue
        version = _PYTHON_VERSION_CLASSIFIER.match(classifier)
        if version is not None and not registry.python_satisfies(
            floor, version.group(1)
        ):
            continue
        inherited.append(classifier)
    return inherited + [c for c in package.classifiers if c not in inherited]


def render_pyproject(package, distributions, meta: RootMetadata) -> str:
    """
    Render a distribution's ``pyproject.toml``.

    Parameters
    ----------
    package : registry.Package
        The distribution's packaging facts.
    distributions : module
        The distribution map (``scikitplot._distributions``).
    meta : RootMetadata
        Inherited root metadata.

    Returns
    -------
    str
        The file content.

    Raises
    ------
    ValueError
        If the registry names a dependency or an extra the root does not
        declare, or re-exports an extra that would install the full
        distribution.
    """
    dist = distributions.get(package.distribution)
    directory = registry.directory_of(dist.name)
    lines = [
        f"# {GENERATED_NOTICE}",
        "#",
        f"# Package metadata of `{dist.name}`: a partial distribution of the",
        "# `scikitplot` import package. Which files it ships is decided by",
        "# scikitplot/_distributions.py; setup.py stages them at build time.",
        "",
        "[build-system]",
        f"requires = {_array(_build_requires(package, meta))}",
        'build-backend = "setuptools.build_meta"',
        "",
        "[project]",
        f"name = {_string(dist.name)}",
        f"version = {_string(meta.version)}",
        f"description = {_string(dist.summary)}",
        (
            f"readme = {{file = {_string(readme_name(directory))}, "
            'content-type = "text/markdown"}'
        ),
        f"requires-python = {_string(package.requires_python or meta.requires_python)}",
        # The licence is declared by setup.py. Its two spellings do not
        # overlap: an SPDX string needs setuptools >= 77, which does not exist
        # for Python 3.8, and the older table form stops being accepted in
        # 2027. setup.py picks the one the running setuptools understands.
        'dynamic = ["license"]',
        f"authors = {_people(meta.authors)}",
        f"maintainers = {_people(meta.maintainers)}",
        f"keywords = {_array(package.keywords)}",
        f"classifiers = {_array(_classifiers(package, meta))}",
        f"dependencies = {_array(_dependencies(package, distributions, meta))}",
    ]
    optional = _optional_dependencies(package, distributions, meta)
    if optional:
        lines += ["", "[project.optional-dependencies]"]
        lines += [f"{name} = {_array(reqs)}" for name, reqs in optional.items()]
    lines += ["", "[project.urls]"]
    lines += [f"{name} = {_string(url)}" for name, url in meta.urls.items()]
    if package.scripts:
        lines += ["", "[project.scripts]"]
        lines += [
            f"{name} = {_string(target)}" for name, target in meta.scripts.items()
        ]
    lines += [
        "",
        "[tool.setuptools]",
        "# Files are listed explicitly by setup.py; MANIFEST.in decides the sdist only.",
        "include-package-data = false",
        "",
    ]
    return "\n".join(lines)


