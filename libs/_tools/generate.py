def render_libs_readme(packages, distributions) -> str:
    """
    Render ``libs/README.md``, the overview of every partial distribution.

    Parameters
    ----------
    packages : sequence of registry.Package
        Every package, in order.
    distributions : module
        The distribution map.

    Returns
    -------
    str
        Markdown.
    """
    rows = []
    for package in packages:
        dist = distributions.get(package.distribution)
        directory = registry.directory_of(dist.name)
        ships = ", ".join(f"`{tree.replace('/', '.')}`" for tree in dist.trees)
        kind = "compiled (C++)" if package.extensions else "pure Python"
        rows.append(
            f"| [`{directory}/`]({directory}/) | `{dist.name}` | {ships} | {kind} |"
        )
    return "\n".join(
        [
            f"<!-- {GENERATED_NOTICE} -->",
            "",
            "# Partial distributions of scikit-plots",
            "",
            (
                f"`{distributions.FULL}` is one large package that needs a compiler "
                "toolchain to build. The directories here publish focused parts of the "
                "same `scikitplot` import package as separate, small distributions, in "
                "the spirit of `mlflow-skinny`."
            ),
            "",
            "| Directory | Distribution | Ships `scikitplot.` | Build |",
            "| --- | --- | --- | --- |",
            *rows,
            "",
            "## How it works",
            "",
            (
                "- **One source tree.** Nothing is copied into `libs/` permanently. Each "
                "`setup.py` stages the files its distribution owns at build time and "
                "removes them when the build exits."
            ),
            (
                "- **One owner per file.** `scikitplot/_distributions.py` says which "
                "distribution owns which path, and no path has two owners, so the "
                f"distributions install side by side. `{distributions.CORE}` owns the "
                "root `__init__.py`; the others depend on it."
            ),
            (
                "- **Generated metadata.** Every file in a lib directory is generated "
                "from `scikitplot/_distributions.py`, `libs/_tools/registry.py` and the "
                "root `pyproject.toml`. Version specifiers are inherited from the root, "
                "so they cannot drift."
            ),
            "",
            "## Commands",
            "",
            "Run from the repository root.",
            "",
            "```sh",
            "python -m libs._tools list       # distributions and what they own",
            "python -m libs._tools generate   # rewrite the generated files",
            "python -m libs._tools check      # fail if generated files are stale",
            "python -m libs._tools build      # build every sdist and wheel",
            "python -m libs._tools verify     # build, then install and test them",
            "```",
            "",
            "## See also",
            "",
            "- https://github.com/mlflow/mlflow/blob/master/libs/skinny/README.md",
            "- https://github.com/mlflow/mlflow/blob/master/libs/skinny/README_SKINNY.md",
            "",
        ]
    )


def render_gitignore() -> str:
    """
    Render ``libs/.gitignore``.

    Returns
    -------
    str
        The file content.

    Notes
    -----
    **Developer.** The first rule is kept from the hand-written file: the
    repository ignores ``mlflow`` directories elsewhere, and ``libs/mlflow``
    must not be caught by that. The rest is what a build can leave behind if
    it is interrupted before it cleans up.
    """
    # No trailing slash on the staged package: with one, the rule matches a
    # directory only, and the link the earlier symlink layout put at
    # ``libs/<name>/scikitplot`` is a file to git, so it was not ignored and
    # could be committed (it then fails "build leaves nothing behind").
    residue = [f"/*/{staging.PACKAGE_NAME}", f"/*/{staging.LICENSE_NAME}"]
    residue += [f"/*/{name}/" for name in staging.RESIDUE_DIR_NAMES]
    residue += ["/*/dist/", "/*/*.egg-info/", "__pycache__/"]
    # What ``npm ci`` installs for the Pyodide probe (libs/_tools/pyodide/).
    residue += ["node_modules/"]
    return "\n".join(
        [
            f"# {GENERATED_NOTICE}",
            "!mlflow",
            "# Staged sources and build residue of the partial distributions.",
            *residue,
            "",
        ]
    )


