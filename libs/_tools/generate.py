#: First line of every generated file that has a comment syntax.
GENERATED_NOTICE = (
    "Generated by libs/_tools. Do not edit; run: python -m libs._tools generate"
)

_REQUIREMENT_NAME = re.compile(r"^\s*([A-Za-z0-9][A-Za-z0-9._-]*)")


class RootMetadata(NamedTuple):
    """
    What every partial distribution inherits from the root project.

    Parameters
    ----------
    version : str
        The version in ``scikitplot/__init__.py``.
    requires_python : str
        Root ``requires-python``.
    authors, maintainers : tuple of dict
        Root ``authors`` and ``maintainers``.
    urls, scripts : dict of str to str
        Root ``[project.urls]`` and ``[project.scripts]``.
    dependencies : tuple of str
        Root ``[project.dependencies]``.
    build_requires : tuple of str
        Root ``[build-system].requires``.
    extras : dict of str to tuple of str
        Root ``[project.optional-dependencies]``.
    classifiers : tuple of str
        Root ``classifiers``.
    """

    version: str
    requires_python: str
    authors: tuple[dict[str, str], ...]
    maintainers: tuple[dict[str, str], ...]
    urls: dict[str, str]
    scripts: dict[str, str]
    dependencies: tuple[str, ...]
    build_requires: tuple[str, ...]
    extras: dict[str, tuple[str, ...]]
    classifiers: tuple[str, ...]


def _load_toml(path: Path) -> dict:
    """Parse a TOML file with the standard library, or its backport."""
    try:
        import tomllib  # Python >= 3.11  # noqa: PLC0415
    except ModuleNotFoundError:
        try:
            import tomli as tomllib  # noqa: PLC0415
        except ModuleNotFoundError as exc:
            raise ModuleNotFoundError(
                "libs/_tools needs a TOML parser to read the root pyproject.toml: "
                "use Python >= 3.11, or run: pip install tomli"
            ) from exc
    with path.open("rb") as handle:
        return tomllib.load(handle)


def read_version(root: Path) -> str:
    """
    Return the version declared in ``scikitplot/__init__.py``.

    Parameters
    ----------
    root : pathlib.Path
        Repository root.

    Returns
    -------
    str
        The first module-level ``__version__ = "<literal>"``.

    Raises
    ------
    ValueError
        If there is no such assignment, or its value is not a non-empty
        string literal.

    Notes
    -----
    **Developer.** This is the assignment the full distribution's build reads
    (``scikitplot/_build_utils/gitversion.py``), found by parsing rather than
    by importing, so the package is never executed to build one of its parts.
    """
    path = root / staging.PACKAGE_NAME / "__init__.py"
    tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
    for node in tree.body:
        if not isinstance(node, ast.Assign):
            continue
        targets = [t.id for t in node.targets if isinstance(t, ast.Name)]
        if "__version__" not in targets:
            continue
        value = node.value
        if (
            isinstance(value, ast.Constant)
            and isinstance(value.value, str)
            and value.value
        ):
            return value.value
        raise ValueError(f"{path}: __version__ is not a non-empty string literal")
    raise ValueError(f"{path}: no module-level __version__ assignment found")


def read_root_metadata(root: Path) -> RootMetadata:
    """
    Read the inherited metadata from the root project.

    Parameters
    ----------
    root : pathlib.Path
        Repository root.

    Returns
    -------
    RootMetadata

    Raises
    ------
    KeyError
        If the root ``pyproject.toml`` lacks a field that is inherited.
    """
    document = _load_toml(root / "pyproject.toml")
    project = document["project"]
    return RootMetadata(
        version=read_version(root),
        requires_python=project["requires-python"],
        authors=tuple(dict(entry) for entry in project["authors"]),
        maintainers=tuple(dict(entry) for entry in project["maintainers"]),
        urls=dict(project["urls"]),
        scripts=dict(project["scripts"]),
        dependencies=tuple(project["dependencies"]),
        build_requires=tuple(document["build-system"]["requires"]),
        extras={
            name: tuple(requirements)
            for name, requirements in project["optional-dependencies"].items()
        },
        classifiers=tuple(project["classifiers"]),
    )


def requirement_name(requirement: str) -> str:
    """
    Return the canonical project name of a requirement string.

    Parameters
    ----------
    requirement : str
        A dependency specifier, e.g. ``'numpy>=2.0.0; python_version >= "3.9"'``.

    Returns
    -------
    str
        The project name in canonical form, e.g. ``"numpy"``.

    Raises
    ------
    ValueError
        If the string does not start with a project name.
    """
    match = _REQUIREMENT_NAME.match(requirement)
    if match is None:
        raise ValueError(f"cannot read a project name from requirement {requirement!r}")
    return staging.load_distributions().canonicalize_name(match.group(1))


def inherit_requirements(
    names: Sequence[str],
    dependencies: Sequence[str],
    table: str = "[project.dependencies]",
) -> list[str]:
    """
    Return the root requirement lines for the named projects, verbatim.

    Parameters
    ----------
    names : sequence of str
        Project names to inherit.
    dependencies : sequence of str
        The root requirement list to inherit from.
    table : str, optional
        The name of that list in the root ``pyproject.toml``, for the error
        message.

    Returns
    -------
    list of str
        Every root line for each name, in root order, grouped by ``names``
        order. A project with several marker-specific lines yields them all.

    Raises
    ------
    ValueError
        If a name has no line in the root list. Inheriting is the only way a
        partial distribution gets a specifier for a shared dependency, so a
        missing one is a mistake in the registry, not something to guess.
    """
    canonicalize = staging.load_distributions().canonicalize_name
    lines: list[str] = []
    for name in names:
        wanted = canonicalize(name)
        found = [line for line in dependencies if requirement_name(line) == wanted]
        if not found:
            raise ValueError(
                f"{name!r} is not declared in the root {table}; declare it "
                "there, or write the requirement in full in the registry"
            )
        lines.extend(found)
    return lines


def readme_name(directory: str) -> str:
    """Return the package-description file name for a lib directory."""
    return f"README_{directory.upper()}.md"


