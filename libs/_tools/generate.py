"""
Generate the packaging files of every partial distribution.

Inputs, each the single home of the facts it holds:

* ``scikitplot/_distributions.py``: which files a distribution owns;
* ``libs/_tools/registry.py``: how a distribution is packaged;
* the root ``pyproject.toml``: shared metadata, and every version specifier;
* ``scikitplot/__init__.py``: the version.

Outputs, per ``libs/<name>/``: ``pyproject.toml``, ``setup.py``,
``MANIFEST.in``, ``README.md`` and ``README_<NAME>.md``; plus
``libs/README.md`` and ``libs/.gitignore``.

Notes
-----
**User.** Run ``python -m libs._tools generate`` from the repository root after
changing any input, and commit the result. ``python -m libs._tools check``
exits non-zero when the files on disk differ from what the inputs produce.

**Developer.** Generation is a pure function of the inputs: no timestamps, no
environment, sorted iteration. Running it twice writes nothing the second
time, and that is what lets ``check`` compare bytes.
"""

from __future__ import annotations

import ast
import json
import re
from pathlib import Path
from typing import NamedTuple, Sequence

from . import registry, staging

